'use client'

import { format } from "date-fns"
import { SparkleIcon } from "@phosphor-icons/react"
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from "@/components/ui/card"
import SummaryRefreshButton from "@/components/summary-refresh-button"
import { useGenerateSummary } from "@/hooks/use-generate-summary"
import { cn } from "@/lib/utils"
import { AISummary } from "@/types/ai-summary"

type ProgramAiSummaryCardProps = {
  aiSummary?: AISummary
  programId?: string
  athleteId?: string
}

export default function ProgramAiSummaryCard({ aiSummary, programId, athleteId }: ProgramAiSummaryCardProps) {

  const { mutate, isPending, error } = useGenerateSummary(programId ?? "", athleteId ?? "")
  const canGenerate = Boolean(programId && athleteId)

  return (
    <Card className="h-full">
      <CardHeader>
        <CardTitle className="flex items-center gap-2">
          <SparkleIcon />
          AI SUMMARY
        </CardTitle>
        <CardDescription>Overview of the program, generated by AI</CardDescription>
      </CardHeader>
      <CardContent className="flex flex-1 flex-col items-center justify-center gap-2">
        {/* The previous summary stays on screen while the new one is generated (and if generating fails). */}
        <p className={cn("m-0 text-sm text-muted-foreground transition-opacity", isPending && "opacity-50")}>
          {aiSummary?.content ? aiSummary.content : "The summary will appear here."}
        </p>
        {isPending && aiSummary?.content && (
          <p className="m-0 text-xs text-muted-foreground">Previous summary shown while a new one is generated.</p>
        )}
        {!isPending && aiSummary?.updatedAt && (
          <p className="m-0 text-xs text-muted-foreground">
            Last updated {format(new Date(aiSummary.updatedAt), "MMM d, yyyy")}
          </p>
        )}
        {canGenerate && (
          <SummaryRefreshButton
            hasSummary={Boolean(aiSummary?.content)}
            isPending={isPending}
            error={error}
            onGenerate={() => mutate()}
          />
        )}
      </CardContent>
    </Card>
  )

}
